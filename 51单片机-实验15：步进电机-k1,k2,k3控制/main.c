/**************************************************************************************
* 实验现象：
*       下载程序后，步进电机自动旋转
*
*       K1：改变电机旋转方向
*       K2：电机加速
*       K3：电机减速
*
* 接线说明：
*       1，单片机-->四线双极性步进电机模块
*               P10-->IA
*               P11-->IB
*               P12-->IC
*               P13-->ID
*
*       2，开发板按键-->单片机
*               K1-->P30
*               K2-->P31
*               K3-->P32
*
***************************************************************************************/

#include "reg52.h"


typedef unsigned int u16;
typedef unsigned char u8;


/*==================== 电机引脚 ====================*/

sbit MOTOA = P1^0;
sbit MOTOB = P1^1;
sbit MOTOC = P1^2;
sbit MOTOD = P1^3;


/*==================== 按键 ====================*/

sbit K1 = P3^0;
sbit K2 = P3^1;
sbit K3 = P3^2;


/*==================== 电机参数 ====================*/

/*
 * SPEED越小，电机越快
 * SPEED越大，电机越慢
 */
u16 SPEED = 200;


/*
 * direction = 1：正转
 * direction = 0：反转
 */
bit direction = 1;


/*******************************************************************************
* 函数名       : delay
* 函数功能     : 延时函数
*******************************************************************************/
void delay(u16 i)
{
    while(i--);
}


/*******************************************************************************
* 函数名       : motor_forward
* 函数功能     : 电机正转
*******************************************************************************/
void motor_forward()
{
    MOTOA = 1;
    MOTOB = 0;
    MOTOC = 1;
    MOTOD = 1;
    delay(SPEED);

    MOTOA = 1;
    MOTOB = 1;
    MOTOC = 1;
    MOTOD = 0;
    delay(SPEED);

    MOTOA = 0;
    MOTOB = 1;
    MOTOC = 1;
    MOTOD = 1;
    delay(SPEED);

    MOTOA = 1;
    MOTOB = 1;
    MOTOC = 0;
    MOTOD = 1;
    delay(SPEED);
}


/*******************************************************************************
* 函数名       : motor_reverse
* 函数功能     : 电机反转
*******************************************************************************/
void motor_reverse()
{
    MOTOA = 1;
    MOTOB = 1;
    MOTOC = 0;
    MOTOD = 1;
    delay(SPEED);

    MOTOA = 0;
    MOTOB = 1;
    MOTOC = 1;
    MOTOD = 1;
    delay(SPEED);

    MOTOA = 1;
    MOTOB = 1;
    MOTOC = 1;
    MOTOD = 0;
    delay(SPEED);

    MOTOA = 1;
    MOTOB = 0;
    MOTOC = 1;
    MOTOD = 1;
    delay(SPEED);
}


/*******************************************************************************
* 函数名       : key_scan
* 函数功能     : 按键扫描
*******************************************************************************/
void key_scan()
{
    /*==================== K1：改变方向 ====================*/

    if(K1 == 0)
    {
        delay(1000);

        if(K1 == 0)
        {
            direction = !direction;

            while(K1 == 0);
        }
    }


    /*==================== K2：加速 ====================*/

    if(K2 == 0)
    {
        delay(1000);

        if(K2 == 0)
        {
            /*
             * SPEED越小，电机越快
             *
             * 所以K2按下后减小SPEED
             */
            if(SPEED >= 80)
            {
                SPEED = SPEED - 30;
            }

            while(K2 == 0);
        }
    }


    /*==================== K3：减速 ====================*/

    if(K3 == 0)
    {
        delay(1000);

        if(K3 == 0)
        {
            /*
             * SPEED越大，电机越慢
             *
             * 所以K3按下后增加SPEED
             */
            if(SPEED <= 470)
            {
                SPEED = SPEED + 30;
            }

            while(K3 == 0);
        }
    }
}


/*******************************************************************************
* 主函数
*******************************************************************************/
void main()
{
    /*
     * P1.0~P1.3用于控制步进电机
     */
    P1 = 0x00;


    /*
     * P3.0~P3.2作为输入
     *
     * 51单片机中给IO写1，可以让其作为输入使用
     */
    K1 = 1;
    K2 = 1;
    K3 = 1;


    while(1)
    {
        /*
         * 检查K1、K2、K3
         */
        key_scan();


        /*
         * 根据方向控制电机
         */
        if(direction == 1)
        {
            motor_forward();
        }
        else
        {
            motor_reverse();
        }
    }
}